    [Fact]
    public async Task Register_to_idempotent_sale_flow_works_against_real_postgres()
    {
        if (!_dbAvailable) { _output.WriteLine("DB not available - skipped."); return; }

        // 1. Manager: set PIN, create register (explicit DbSet.Add), get activation code.
        var setPin = await WithRegisterService(s => s.SetPinAsync(Admin, _cashierId));
        Assert.Null(setPin.Error);
        _pin = setPin.Result!.Pin;
        Assert.Matches("^[0-9]{6}$", _pin);

        var (created, createErr, _) = await WithRegisterService(s =>
            s.CreateAsync(Admin, new CreateRegisterRequest(_storeId, "Каса 1")));
        Assert.Null(createErr);
        Assert.Equal(1, created!.Register.Number);

        // 2. Device: single-use activation (conditional UPDATE) - second use fails.
        var (activated, actErr, _) = await WithRegisterService(s =>
            s.ActivateAsync(new ActivateRegisterRequest(created.ActivationCode, "1.0.0-test")));
        Assert.Null(actErr);
        var replay = await WithRegisterService(s => s.ActivateAsync(new ActivateRegisterRequest(created.ActivationCode)));
        Assert.Equal(400, replay.StatusCode);

        // 3. Operator: PIN-only sign-in with real bcrypt inside a tenant-scoped transaction.
        var wrong = await WithRegisterService(s =>
            s.StartSessionAsync(activated!.DeviceToken, new StartSessionRequest("0000")));
        Assert.Equal(401, wrong.StatusCode);
        var (session, sessErr, _) = await WithRegisterService(s =>
            s.StartSessionAsync(activated!.DeviceToken, new StartSessionRequest(_pin)));
        Assert.Null(sessErr);
        Assert.Equal(_cashierId, session!.CashierId);
        Assert.False(string.IsNullOrEmpty(session.AccessToken));

        await using (var verify = NewContext())
        {
            var reg = await verify.CashRegisters.AsNoTracking().SingleAsync(r => r.Id == created.Register.Id);
            Assert.Equal(CashRegister.StatusActive, reg.Status);
            Assert.Null(reg.ActivationCodeHash);
            Assert.NotNull(reg.DeviceTokenHash);
            Assert.Equal("1.0.0-test", reg.AppVersion);
            Assert.Equal(1, reg.PinFailCount); // the earlier wrong PIN is still counted: success never resets it
            var s = await verify.RegisterSessions.AsNoTracking().SingleAsync(x => x.RegisterId == reg.Id);
            Assert.Equal(_cashierId, s.CashierId);
            Assert.Null(s.EndedAt);
        }

        var registerId = created.Register.Id;

        // 4. Register-bound shift, then the same ClientTransactionId twice from two "requests".
        var (shift, shiftErr, _) = await WithPos(p => p.OpenShiftAsync(
            _tenantId, _cashierId, new OpenShiftRequest(_storeId, 100m), default, registerId));
        Assert.Null(shiftErr);

        var clientId = Guid.NewGuid();
        var request = new CreateSaleRequest(
            shift!.ShiftId, [new SaleItemRequest(Barcode, 2)], "Cash", 100m, ClientTransactionId: clientId);

        var first = await WithPos(p => p.CreateSaleAsync(_tenantId, _cashierId, request, default, registerId));
        var second = await WithPos(p => p.CreateSaleAsync(_tenantId, _cashierId, request, default, registerId));
        Assert.Null(first.Error);
        Assert.Null(second.Error);
        Assert.Equal(first.Sale!.TransactionId, second.Sale!.TransactionId);

        await using (var verify = NewContext())
        {
            var txs = await verify.PosTransactions.AsNoTracking()
                .Where(t => t.TenantId == _tenantId).ToListAsync();
            var tx = Assert.Single(txs);
            Assert.Equal(registerId, tx.CashRegisterId);
            Assert.Equal(clientId, tx.ClientTransactionId);
            Assert.Equal(8m, (await verify.ProductStocks.AsNoTracking().SingleAsync(s => s.Id == _stockId)).Quantity);
            Assert.Equal(registerId, (await verify.PosShifts.AsNoTracking().SingleAsync(s => s.Id == shift.ShiftId)).RegisterId);
        }

        // A second register in the same store can open its own shift (per-register shifts).
        var (reg2, _, _) = await WithRegisterService(s =>
            s.CreateAsync(Admin, new CreateRegisterRequest(_storeId, "Каса 2")));
        var shift2 = await WithPos(p => p.OpenShiftAsync(
            _tenantId, _cashierId, new OpenShiftRequest(_storeId), default, reg2!.Register.Id));
        Assert.Null(shift2.Error);

        // 5. Batch: replay (duplicate), new sale (created), unknown barcode (failed) - partial failure.
        var newId = Guid.NewGuid();
        var batch = new BatchSalesRequest(
        [
            request,
            new CreateSaleRequest(shift.ShiftId, [new SaleItemRequest(Barcode, 1)], "Cash", 50m, ClientTransactionId: newId),
            new CreateSaleRequest(shift.ShiftId, [new SaleItemRequest("NO-" + _run, 1)], "Cash", 50m, ClientTransactionId: Guid.NewGuid()),
        ]);
        var (result, batchErr, _) = await WithPos(p => p.CreateSalesBatchAsync(
            _tenantId, _cashierId, batch, default, registerId));
        Assert.Null(batchErr);
        Assert.Equal(["duplicate", "created", "failed"], result!.Results.Select(r => r.Status).ToArray());

        await using (var verify = NewContext())
        {
            Assert.Equal(2, await verify.PosTransactions.CountAsync(t => t.TenantId == _tenantId));
            Assert.Equal(7m, (await verify.ProductStocks.AsNoTracking().SingleAsync(s => s.Id == _stockId)).Quantity);
        }

        // 6. DB-level backstop: the unique (TenantId, ClientTransactionId) index is translated.
        await using (var dbA = NewContext())
        await using (var dbB = NewContext())
        {
            var repoA = new PosRepository(dbA);
            var repoB = new PosRepository(dbB);
            var dup = Guid.NewGuid();
            PosTransaction Make() => new()
            {
                TenantId = _tenantId, StoreId = _storeId, ShiftId = shift.ShiftId,
                ReceiptNumber = "R-" + Guid.NewGuid().ToString("N")[..12], ClientTransactionId = dup,
            };
            await repoA.AddTransactionAsync(Make());
            await repoA.SaveChangesAsync();
            await repoB.AddTransactionAsync(Make());
            await Assert.ThrowsAsync<DuplicateClientTransactionException>(() => repoB.SaveChangesAsync());
        }

        // 7. End the session.
        var ended = await WithRegisterService(s => s.EndSessionAsync(session.SessionId, registerId, "logout"));
        Assert.True(ended.Ok);
        await using (var verify = NewContext())
            Assert.NotNull((await verify.RegisterSessions.AsNoTracking().SingleAsync(x => x.Id == session.SessionId)).EndedAt);
    }

    [Fact]
    public async Task Item_updates_bump_UpdatedAt_via_trigger_and_show_up_in_delta_catalog()
    {
        if (!_dbAvailable) { _output.WriteLine("DB not available - skipped."); return; }

        DateTime before;
        await using (var db = NewContext())
            before = (await db.Items.AsNoTracking().SingleAsync(i => i.Id == _itemId)).UpdatedAt;

        await Task.Delay(50);
        await using (var db = NewContext())
        {
            var item = await db.Items.SingleAsync(i => i.Id == _itemId);
            item.PriceRetail = 77m;
            await db.SaveChangesAsync(); // plain EF update - the trigger must bump UpdatedAt
        }

        await using (var db = NewContext())
        {
            var svc = new PosSyncService(new CatalogSyncRepository(db));
            var page = await svc.GetCatalogAsync(before, null, 2000);

            var row = Assert.Single(page.Items, i => i.Id == _itemId);
            Assert.Equal(77m, row.PriceRetail);
            Assert.True(row.UpdatedAt > before);
            Assert.Contains(Barcode, row.Barcodes);

            // The cursor excludes what was already delivered.
            var next = await svc.GetCatalogAsync(row.UpdatedAt, _itemId, 2000);
            Assert.DoesNotContain(next.Items, i => i.Id == _itemId);
        }
    }

    [Fact]
    public async Task New_tables_have_force_rls_and_the_canonical_policy_triad()
    {
        if (!_dbAvailable) { _output.WriteLine("DB not available - skipped."); return; }

        await using var conn = new NpgsqlConnection(_cs);
        await conn.OpenAsync();

        foreach (var table in new[] { "cash_registers", "register_sessions" })
        {
            await using var flags = new NpgsqlCommand(
                "SELECT relrowsecurity, relforcerowsecurity FROM pg_class WHERE relname = @t", conn);
            flags.Parameters.AddWithValue("t", table);
            await using (var r = await flags.ExecuteReaderAsync())
            {
                Assert.True(await r.ReadAsync());
                Assert.True(r.GetBoolean(0), $"{table}: RLS not enabled");
                Assert.True(r.GetBoolean(1), $"{table}: RLS not forced");
            }

            await using var pol = new NpgsqlCommand(
                "SELECT policyname, qual FROM pg_policies WHERE tablename = @t ORDER BY policyname", conn);
            pol.Parameters.AddWithValue("t", table);
            var policies = new Dictionary<string, string>();
            await using (var r = await pol.ExecuteReaderAsync())
                while (await r.ReadAsync()) policies[r.GetString(0)] = r.GetString(1);

            Assert.Equal(["provider_bypass", "tenant_isolation", "worker_bypass"], policies.Keys.Order().ToArray());
            Assert.Contains("NULLIF", policies["tenant_isolation"], StringComparison.OrdinalIgnoreCase);
        }
    }

    [Fact]
    public async Task Concurrent_pin_failures_are_counted_atomically()
    {
        if (!_dbAvailable) { _output.WriteLine("DB not available - skipped."); return; }

        var (created, _, _) = await WithRegisterService(s =>
            s.CreateAsync(Admin, new CreateRegisterRequest(_storeId, "Race")));
        var id = created!.Register.Id;

        const int parallel = 12;
        var now = DateTime.UtcNow;
        var outcomes = await Task.WhenAll(Enumerable.Range(0, parallel).Select(async _ =>
        {
            await using var db = NewContext();
            return await new CashRegisterRepository(db).RegisterPinFailureAsync(
                id, now, RegisterService.RegisterWindow, RegisterService.MaxRegisterDailyAttempts);
        }));

        // No lost updates: every increment from 1..12 was handed out exactly once.
        Assert.Equal(Enumerable.Range(1, parallel), outcomes.Select(o => o.WindowCount).Order());
        await using var verify = NewContext();
        var reg = await verify.CashRegisters.AsNoTracking().SingleAsync(r => r.Id == id);
        Assert.Equal(parallel, reg.PinFailCount);
        Assert.Equal(parallel, reg.PinFailDailyCount);

        // A failure after the window elapsed restarts the window (decay) but keeps the daily count.
        await using var db2 = NewContext();
        var later = await new CashRegisterRepository(db2).RegisterPinFailureAsync(
            id, now.AddMinutes(20), RegisterService.RegisterWindow, RegisterService.MaxRegisterDailyAttempts);
        Assert.Equal(1, later.WindowCount);
        Assert.Equal(parallel + 1, later.DailyCount);
    }

    [Fact]
    public async Task Operator_session_validator_follows_session_register_user_and_module_state()
    {
        if (!_dbAvailable) { _output.WriteLine("DB not available - skipped."); return; }

        var pin = (await WithRegisterService(s => s.SetPinAsync(Admin, _cashierId))).Result!.Pin;
        var (created, _, _) = await WithRegisterService(s =>
            s.CreateAsync(Admin, new CreateRegisterRequest(_storeId, "Val")));
        var activated = (await WithRegisterService(s =>
            s.ActivateAsync(new ActivateRegisterRequest(created!.ActivationCode)))).Result!;
        var registerId = created.Register.Id;

        async Task<RegisterSessionResponse> SignIn() =>
            (await WithRegisterService(s => s.StartSessionAsync(activated.DeviceToken, new StartSessionRequest(pin)))).Result!;
        OperatorSessionValidator Fresh() =>
            new(_sp!.GetRequiredService<IServiceScopeFactory>(), new MemoryCache(new MemoryCacheOptions()));
        // Fresh validator = no cache, so each assertion reflects the database.
        async Task<bool> Valid(RegisterSessionResponse x) =>
            await Fresh().IsValidAsync(_tenantId, x.SessionId, registerId, _cashierId);

        var first = await SignIn();
        Assert.True(await Valid(first));

        // Replaced by a new sign-in -> old token dead.
        var second = await SignIn();
        Assert.False(await Valid(first));
        Assert.True(await Valid(second));

        // The cached verdict is dropped immediately on end (no 30 s grace).
        Assert.True(await _validator!.IsValidAsync(_tenantId, second.SessionId, registerId, _cashierId)); // primes cache
        await WithRegisterService(s => s.EndSessionAsync(second.SessionId, registerId, "logout"));
        Assert.False(await _validator.IsValidAsync(_tenantId, second.SessionId, registerId, _cashierId));

        // Deactivated user, locked register, module off: each kills a live session.
        var third = await SignIn();
        Assert.True(await Valid(third));
        await using (var db = NewContext())
        {
            await db.Database.ExecuteSqlRawAsync("UPDATE users SET \"IsActive\" = false WHERE \"Id\" = {0}", _cashierId);
            Assert.False(await Valid(third));
            await db.Database.ExecuteSqlRawAsync("UPDATE users SET \"IsActive\" = true WHERE \"Id\" = {0}", _cashierId);
            Assert.True(await Valid(third));

            await db.Database.ExecuteSqlRawAsync("UPDATE cash_registers SET \"Status\" = 'locked' WHERE \"Id\" = {0}", registerId);
            Assert.False(await Valid(third));
            await db.Database.ExecuteSqlRawAsync("UPDATE cash_registers SET \"Status\" = 'active' WHERE \"Id\" = {0}", registerId);

            await db.Database.ExecuteSqlRawAsync("UPDATE tenants SET \"Modules\" = '[\"inventory\"]' WHERE \"Id\" = {0}", _tenantId);
            Assert.False(await Valid(third));
            await db.Database.ExecuteSqlRawAsync("UPDATE tenants SET \"Modules\" = '[\"inventory\",\"pos\"]' WHERE \"Id\" = {0}", _tenantId);
            Assert.True(await Valid(third));
        }

        // A token claiming a different register than the session row is rejected.
        Assert.False(await Fresh().IsValidAsync(_tenantId, third.SessionId, Guid.NewGuid(), _cashierId));

        await WithRegisterService(s => s.RevokeAsync(Admin, registerId));
        Assert.False(await Valid(third));
    }

    // ── helpers ──────────────────────────────────────────────────────────

    private AppDbContext NewContext() => TestPostgres.NewContext(_cs);

    private static readonly IConfiguration JwtConfig = new ConfigurationBuilder()
        .AddInMemoryCollection(new Dictionary<string, string?> { ["Jwt:Secret"] = new string('k', 48) })
        .Build();

    private async Task<T> WithRegisterService<T>(Func<RegisterService, Task<T>> action)
    {
        await using var db = NewContext(); // one context per simulated request
        var svc = new RegisterService(
            new CashRegisterRepository(db),
            new UserRepository(db),
            new UserLocationRepository(db),
            new LocationRepository(db),
            new TenantRepository(db),
            new BcryptPasswordHasher(),
            new JwtService(JwtConfig),
            new TenantSessionOverride(db),
            new RandomPinGenerator(),
            _validator!,
            NullLogger<RegisterService>.Instance);
        return await action(svc);
    }

    private async Task<T> WithPos<T>(Func<PosService, Task<T>> action)
    {
        await using var db = NewContext();
        var svc = new PosService(
            new PosRepository(db),
            new StockRepository(db),
            new ItemRepository(db),
            new DiscountRepository(db),
            new StaticFiscalFactory(new NoopFiscalService()),
            new LoyaltyRepository(db),
            new CustomerRepository(db),
            NullLogger<PosService>.Instance);
        return await action(svc);
    }

    private sealed class StaticFiscalFactory(IFiscalService service) : IFiscalServiceFactory
    {
        public PrroConnectionConfig? EnvFallback => null;
        public Task<IFiscalService> GetForTenantAsync(Guid tenantId, CancellationToken ct = default) =>
            Task.FromResult(service);
        public IFiscalService Create(Guid tenantId, PrroConnectionConfig config) => service;
    }
