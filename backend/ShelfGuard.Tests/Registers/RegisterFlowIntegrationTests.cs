/// <summary>
/// Real-Postgres flow for the cashier-app backend (mocked tests alone have missed EF bugs before,
/// e.g. a Guid-keyed entity added via a navigation collection being marked Modified -> UPDATE 0 rows).
/// Drives the real repositories + services end to end on separate DbContexts (one per "request"):
/// create register (explicit DbSet.Add) -> single-use activation (conditional ExecuteUpdate) ->
/// PIN session (real bcrypt, tenant-scoped transaction) -> register-bound shift -> idempotent sale
/// (unique index backstop) -> batch with replay/failure -> delta catalog (items.UpdatedAt trigger)
/// -> RLS policy shape on the two new tables.
///
/// Connects as the <c>crm</c> superuser (bypasses RLS: SQL/EF correctness under test, not tenant
/// isolation - the policy shape is asserted structurally from pg_policies). Soft-skips when no
/// reachable Postgres, like the other integration tests.
/// </summary>
public sealed class RegisterFlowIntegrationTests : IAsyncLifetime
{
