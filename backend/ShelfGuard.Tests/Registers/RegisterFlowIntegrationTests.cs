        }
        catch (Exception ex)
        {
            _output.WriteLine($"Skipping register flow integration test - no Postgres at '{_cs}': {ex.Message}");
            return;
        }

        await using var db = NewContext();
        var tenant = Tenant.Create($"Register Flow {_run}", $"register-flow-{_run}");
        tenant.UpdateModules(["inventory", "pos"]);
        _tenantId = tenant.Id;

        var store = new Location { Id = _storeId, TenantId = tenant.Id, Name = "Register Flow Store" };
        var cashier = User.Create(tenant.Id, $"cashier-{_run}@flow.test", "Flow Cashier", "pw", AppRoles.Cashier, _storeId);
        _cashierId = cashier.Id;

        var item = new Item { TenantId = tenant.Id, Name = "Flow Item", Barcodes = [Barcode], PriceRetail = 50m };
        var stock = new ProductStock
        {
            TenantId = tenant.Id, ProductId = item.Id, StoreId = _storeId,
            Quantity = 10m, QuantityInitial = 10m,
            ExpiryDate = DateOnly.FromDateTime(DateTime.UtcNow.AddDays(30)), Status = "safe",
